/** Модель узлов рисовалки плана (совместима с docs/business/venue-plan.example.json). */

export type PlanNodeKind =
  | "rect"
  | "ellipse"
  | "line"
  | "polygon"
  | "path"
  | "emoji"
  | "text";

export type PlanNodeRole = "decor" | "bookable";

export type PlanPoint = { x: number; y: number };

export type PlanFrame = { x: number; y: number; w: number; h: number };

export type PlanNodeStyle = {
  fill: string | null;
  stroke: string;
  strokeWidth: number;
  radius: number;
  opacity: number;
};

export type PlanNode = {
  id: string;
  kind: PlanNodeKind;
  role: PlanNodeRole;
  label: string | null;
  frame?: PlanFrame;
  points?: PlanPoint[];
  /** Внутренние контуры (дыры) после булевых операций. */
  holes?: PlanPoint[][];
  /** Поворот в градусах вокруг центра frame / bbox. */
  rotation?: number;
  /** Общая группа: двигаются вместе (стол + стулья). */
  groupId?: string | null;
  style: PlanNodeStyle;
  zIndex: number;
  bookableId: string | null;
};

export type PlanDocument = {
  id: string;
  floorKey: string;
  label: string;
  version: number;
  status: "draft" | "published";
  canvas: { width: number; height: number; background: string };
  nodes: PlanNode[];
};

export type EditorTool =
  | "select"
  | "rect"
  | "ellipse"
  | "line"
  | "polygon"
  | "emoji"
  | "text"
  | "pan";

